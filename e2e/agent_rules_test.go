func (e *env) configureRules(kind string) (string, string) {
	e.t.Helper()
	source := e.configureContext(kind)
	e.writeFile(filepath.Join(source, "agent-rules.md"), "Context rules for "+e.user.name+" "+kind+".\n")
	e.git(source, "add", "agent-rules.md")
	e.git(source, "commit", "--no-gpg-sign", "-m", "Add context rules")
	template := filepath.Join(e.home, "tooling", "templates", "AGENTS.md")
	e.writeFile(template, "Write every file for the user under `records/`.\n")
	e.writeConfig("owner_prefix = " + strconv.Quote(e.user.ownerPrefix) + "\nagent_rules_template = " + strconv.Quote("~/tooling/templates/AGENTS.md") + "\n[types." + kind + "]\ncontext = " + strconv.Quote(source) + "\n")
	return source, template
}

func TestAgentRulesCreate(t *testing.T) {
	forEachUser(t, func(t *testing.T, e *env) {
		for _, kind := range []string{"work", "priv"} {
			t.Run(kind, func(t *testing.T) {
				e := newEnv(t, e.user)
				e.createRepo("svc-auth")
				e.init()
				source, template := e.configureRules(kind)
				e.mustGW("create", "login", "--type", kind, "--repos", "svc-auth")
				ws := e.showWorkspace("login")
				data, err := os.ReadFile(filepath.Join(ws.Path, "AGENTS.md"))
				if err != nil {
					t.Fatal(err)
				}
				rules := string(data)
				for _, want := range []string{"Generated by gw", template, filepath.Join(ws.Path, filepath.Base(source), "agent-rules.md"), "`records/`", "Context rules for " + e.user.name + " " + kind + "."} {
					e.requireContains(rules, want, "generated rules")
				}
				if strings.Index(rules, "`records/`") > strings.Index(rules, "Context rules for") {
					t.Fatal("context rules must follow template rules")
				}
				pointer, err := os.ReadFile(filepath.Join(ws.Path, "CLAUDE.md"))
				if err != nil || string(pointer) != "@AGENTS.md\n" {
					t.Fatalf("Claude pointer = %q, error = %v", pointer, err)
				}
			})
		}
	})
}

func TestAgentRulesRegenerateAfterContextRebase(t *testing.T) {
	forEachUser(t, func(t *testing.T, e *env) {
		for _, command := range []string{"create", "add-repo", "sync"} {
			t.Run(command, func(t *testing.T) {
				e := newEnv(t, e.user)
				e.createRepo("svc-auth")
				e.createRepo("svc-api")
				e.init()
				source, template := e.configureRules("work")
				context := e.worktree("login", filepath.Base(source))
				if command == "create" {
					e.git(source, "branch", e.branch("login"))
				} else {
					e.mustGW("create", "login", "--repos", "svc-auth")
					e.writeFile(filepath.Join(e.workspacePath("login"), "AGENTS.md"), "Local edit gets replaced\n")
					e.writeFile(filepath.Join(e.workspacePath("login"), "CLAUDE.md"), "Local pointer edit\n")
					e.writeFile(filepath.Join(context, "branch-notes.md"), "Keep branch notes\n")
					e.git(context, "add", "branch-notes.md")
					e.git(context, "commit", "--no-gpg-sign", "-m", "Keep workspace notes")
				}
				e.writeFile(filepath.Join(source, "agent-rules.md"), "Updated base rules\n")
				e.git(source, "add", "agent-rules.md")
				e.git(source, "commit", "--no-gpg-sign", "-m", "Update shared rules")
				e.writeFile(template, "Updated template rules\n")
				e.git(source, "config", "commit.gpgsign", "true")
				e.git(source, "config", "gpg.program", "/missing-signing-program")
				switch command {
				case "create":
					e.mustGW("create", "login", "--repos", "svc-auth")
				case "add-repo":
					e.mustGW("add-repo", "login", "--repos", "svc-api")
				case "sync":
					e.mustGWIn(context, "sync")
				}
				data, err := os.ReadFile(filepath.Join(e.workspacePath("login"), "AGENTS.md"))
				if err != nil {
					t.Fatal(err)
				}
				e.requireContains(string(data), "Updated base rules", "regenerated context rules")
				e.requireContains(string(data), "Updated template rules", "regenerated template rules")
				if strings.Contains(string(data), "Local edit") {
					t.Fatal("local edit survived regeneration")
				}
				if got := e.commitsBehind(context, "main"); got != "0" {
					t.Fatalf("context is %s commits behind main", got)
				}
				e.requireExists(filepath.Join(context, "records", "login", "TASK.md"))
				if command != "create" {
					e.requireExists(filepath.Join(context, "branch-notes.md"))
				}
				pointer, err := os.ReadFile(filepath.Join(e.workspacePath("login"), "CLAUDE.md"))
				if err != nil || string(pointer) != "@AGENTS.md\n" {
					t.Fatalf("Claude pointer = %q, error = %v", pointer, err)
				}
			})
		}
	})
}

func TestAgentRulesNoHooks(t *testing.T) {
	forEachUser(t, func(t *testing.T, e *env) {
		e.createRepo("svc-auth")
		e.createRepo("svc-api")
		e.init()
		source, _ := e.configureRules("work")
		e.mustGW("--no-hooks", "create", "without", "--repos", "svc-auth")
		e.requireMissing(filepath.Join(e.workspacePath("without"), "AGENTS.md"))
		e.requireMissing(filepath.Join(e.workspacePath("without"), "CLAUDE.md"))
		e.mustGW("create", "login", "--repos", "svc-auth")
		context := e.worktree("login", filepath.Base(source))
		e.writeFile(filepath.Join(source, "agent-rules.md"), "Updated base rules\n")
		e.git(source, "add", "agent-rules.md")
		e.git(source, "commit", "--no-gpg-sign", "-m", "Update shared rules")
		for _, command := range []string{"add-repo", "sync"} {
			e.writeFile(filepath.Join(e.workspacePath("login"), "AGENTS.md"), "Keep local rules\n")
			e.writeFile(filepath.Join(e.workspacePath("login"), "CLAUDE.md"), "Keep local pointer\n")
			args := []string{"--no-hooks", command, "login"}
			if command == "add-repo" {
				args = append(args, "--repos", "svc-api")
			}
			e.mustGW(args...)
			for name, want := range map[string]string{"AGENTS.md": "Keep local rules\n", "CLAUDE.md": "Keep local pointer\n"} {
				got, err := os.ReadFile(filepath.Join(e.workspacePath("login"), name))
				if err != nil || string(got) != want {
					t.Fatalf("%s after %s = %q, error = %v", name, command, got, err)
				}
			}
			if command == "add-repo" && e.commitsBehind(context, "main") != "1" {
				t.Fatal("disabled add-repo hook rebased context")
			}
		}
		if e.commitsBehind(context, "main") != "0" {
			t.Fatal("disabled rules generation skipped normal sync")
		}
	})
}

func TestAgentRulesFailurePreservesFiles(t *testing.T) {
	forEachUser(t, func(t *testing.T, e *env) {
		for _, command := range []string{"add-repo", "sync"} {
			for _, problem := range []string{"dirty", "conflict", "missing-template", "missing-context", "unexpected-branch"} {
				t.Run(command+"/"+problem, func(t *testing.T) {
					e := newEnv(t, e.user)
					e.createRepo("svc-auth")
					e.createRepo("svc-api")
					e.init()
					source, template := e.configureRules("work")
					e.mustGW("create", "login", "--repos", "svc-auth")
					context := e.worktree("login", filepath.Base(source))
					before := e.git(context, "rev-parse", "HEAD")
					switch problem {
					case "dirty":
						e.writeFile(filepath.Join(context, "notes.md"), "Keep uncommitted notes\n")
					case "conflict":
						e.writeFile(filepath.Join(context, "agent-rules.md"), "Workspace rules\n")
						e.git(context, "add", "agent-rules.md")
						e.git(context, "commit", "--no-gpg-sign", "-m", "Workspace rules")
						before = e.git(context, "rev-parse", "HEAD")
						e.writeFile(filepath.Join(source, "agent-rules.md"), "Conflicting base rules\n")
						e.git(source, "add", "agent-rules.md")
						e.git(source, "commit", "--no-gpg-sign", "-m", "Conflicting base rules")
					case "missing-template":
						if err := os.Remove(template); err != nil {
							t.Fatal(err)
						}
					case "missing-context":
						if err := os.Rename(context, context+"-moved"); err != nil {
							t.Fatal(err)
						}
					case "unexpected-branch":
						e.git(context, "checkout", "-b", "other-branch")
						e.writeFile(filepath.Join(source, "advanced.md"), "Advance base\n")
						e.git(source, "add", "advanced.md")
						e.git(source, "commit", "--no-gpg-sign", "-m", "Advance base")
					}
					e.writeFile(filepath.Join(e.workspacePath("login"), "AGENTS.md"), "Preserve existing rules\n")
					e.writeFile(filepath.Join(e.workspacePath("login"), "CLAUDE.md"), "Preserve existing pointer\n")
					args := []string{command, "login"}
					if command == "add-repo" {
						args = append(args, "--repos", "svc-api")
					}
					e.gw(args...).mustFail(t)
					for name, want := range map[string]string{"AGENTS.md": "Preserve existing rules\n", "CLAUDE.md": "Preserve existing pointer\n"} {
						got, err := os.ReadFile(filepath.Join(e.workspacePath("login"), name))
						if err != nil || string(got) != want {
							t.Fatalf("%s after failure = %q, error = %v", name, got, err)
						}
					}
					if got := e.git(source, "rev-parse", e.branch("login")); got != before {
						t.Fatal("failed regeneration changed the workspace branch")
					}
					if problem == "unexpected-branch" && e.git(source, "rev-parse", "other-branch") != before {
						t.Fatal("sync rebased an unexpected context branch")
					}
					if len(e.showWorkspace("login").Repos) != map[string]int{"sync": 2, "add-repo": 3}[command] {
						t.Fatal("post-hook failure lost a tracked worktree")
					}
				})
			}
		}
	})
}

func TestAgentRulesContextSources(t *testing.T) {
	forEachUser(t, func(t *testing.T, e *env) {
		for _, scenario := range []string{"workspace-branch", "missing-rules", "no-context"} {
			t.Run(scenario, func(t *testing.T) {
				e := newEnv(t, e.user)
				e.createRepo("svc-auth")
				e.createRepo("svc-api")
				e.init()
				source, template := e.configureRules("work")
				switch scenario {
				case "workspace-branch":
					e.git(source, "checkout", "-b", "stable")
					e.writeFile(filepath.Join(source, ".grove.toml"), "base_branch = 'stable'\n")
					e.git(source, "add", ".grove.toml")
					e.git(source, "commit", "--no-gpg-sign", "-m", "Use stable base")
				case "missing-rules":
					e.git(source, "rm", "agent-rules.md")
					e.git(source, "commit", "--no-gpg-sign", "-m", "Remove optional rules")
				case "no-context":
					e.writeConfig("owner_prefix = " + strconv.Quote(e.user.ownerPrefix) + "\nagent_rules_template = " + strconv.Quote(template) + "\n")
				}
				// Init rewrites configuration through Load and Save.
				e.mustGW("init", e.reposDir)
				e.mustGW("create", "login", "--repos", "svc-auth")
				if scenario == "workspace-branch" {
					context := e.worktree("login", filepath.Base(source))
					e.writeFile(filepath.Join(context, "agent-rules.md"), "Workspace branch rules\n")
					e.git(context, "add", "agent-rules.md")
					e.git(context, "commit", "--no-gpg-sign", "-m", "Customize workspace rules")
					e.writeFile(filepath.Join(source, "stable-notes.md"), "New stable notes\n")
					e.git(source, "add", "stable-notes.md")
					e.git(source, "commit", "--no-gpg-sign", "-m", "Advance stable")
					e.mustGW("add-repo", "login", "--repos", "svc-api")
					e.requireExists(filepath.Join(context, "stable-notes.md"))
					if e.commitsBehind(context, "stable") != "0" {
						t.Fatal("context did not rebase onto configured base")
					}
				}
				data, err := os.ReadFile(filepath.Join(e.workspacePath("login"), "AGENTS.md"))
				if err != nil {
					t.Fatal(err)
				}
				e.requireContains(string(data), "`records/`", "template rules after configuration round trip")
				if scenario == "workspace-branch" {
					e.requireContains(string(data), "Workspace branch rules", "context worktree rules")
				}
				if strings.Contains(string(data), "Context rules for") {
					t.Fatal("generation read unexpected context clone rules")
				}
			})
		}
	})
}

func TestAgentRulesCreateFailureKeepsContext(t *testing.T) {
	forEachUser(t, func(t *testing.T, e *env) {
		for _, problem := range []string{"missing-template", "conflict"} {
			t.Run(problem, func(t *testing.T) {
				e := newEnv(t, e.user)
				e.createRepo("svc-auth")
				e.init()
				source, template := e.configureRules("work")
				if problem == "missing-template" {
					if err := os.Remove(template); err != nil {
						t.Fatal(err)
					}
				} else {
					e.git(source, "checkout", "-b", e.branch("login"))
					e.writeFile(filepath.Join(source, "agent-rules.md"), "Workspace rules\n")
					e.git(source, "add", "agent-rules.md")
					e.git(source, "commit", "--no-gpg-sign", "-m", "Workspace rules")
					e.git(source, "checkout", "main")
					e.writeFile(filepath.Join(source, "agent-rules.md"), "Conflicting base rules\n")
					e.git(source, "add", "agent-rules.md")
					e.git(source, "commit", "--no-gpg-sign", "-m", "Conflicting base rules")
				}
				config, err := os.ReadFile(filepath.Join(e.groveDir, "config.toml"))
				if err != nil {
					t.Fatal(err)
				}
				e.writeFile(filepath.Join(e.groveDir, "config.toml"), string(config)+"\n[hooks]\npost_create = 'touch \"$HOME/shell-created\"'\n")
				e.gw("create", "login", "--repos", "svc-auth").mustFail(t)
				ws := e.showWorkspace("login")
				if len(ws.Repos) != 2 {
					t.Fatalf("lost tracked worktrees: %+v", ws.Repos)
				}
				e.requireExists(filepath.Join(ws.Path, "records", "TASK.md"))
				e.requireMissing(filepath.Join(ws.Path, "AGENTS.md"))
				e.requireMissing(filepath.Join(ws.Path, "CLAUDE.md"))
				e.requireMissing(filepath.Join(e.home, "shell-created"))
				context := filepath.Join(ws.Path, filepath.Base(source))
				if got := e.git(context, "status", "--porcelain"); got != "" {
					t.Fatalf("failed generation left a dirty context: %s", got)
				}
				if e.currentBranch(context) != e.branch("login") {
					t.Fatal("failed generation left a rebase in progress")
				}
			})
		}
	})
}
