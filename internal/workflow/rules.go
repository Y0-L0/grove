package workflow

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/nicksenap/grove/internal/contextrepo"
	"github.com/nicksenap/grove/internal/gitops"
	"github.com/nicksenap/grove/internal/lifecycle"
	"github.com/nicksenap/grove/internal/models"
)

// GenerateRules replaces workspace agent files with their configured sources.
func GenerateRules(ws models.Workspace, cfg *models.Config) error {
	if lifecycle.Disabled || cfg == nil || cfg.AgentRulesTemplate == "" {
		return nil
	}
	template, err := contextPath(cfg.AgentRulesTemplate)
	if err != nil {
		return err
	}
	generic, err := os.ReadFile(template)
	if err != nil {
		return fmt.Errorf("reading agent rules template: %w", err)
	}
	var sources, personal string
	for _, repo := range ws.Repos {
		if !repo.Context {
			continue
		}
		if err := rebaseRulesContext(repo); err != nil {
			return fmt.Errorf("updating context before agent rules generation: %w", err)
		}
		source := filepath.Join(repo.WorktreePath, "agent-rules.md")
		data, err := os.ReadFile(source)
		if err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("reading context agent rules: %w", err)
		}
		sources += "> " + source + " for workspaces of type " + ws.Type + ".\n"
		personal += strings.TrimRight(string(data), "\r\n") + "\n"
	}
	header := "> Generated by gw. Do not edit this file:\n" +
		"> gw overwrites it at the next create, add repo, reopen or sync,\n" +
		"> and every change made here is lost.\n" +
		"> Change a rule in its sources instead:\n> " + template + " for every user.\n" + sources
	if err := replaceRulesFile(filepath.Join(ws.Path, "AGENTS.md"), header+"\n"+strings.TrimRight(string(generic), "\r\n")+"\n\n"+personal); err != nil {
		return err
	}
	return replaceRulesFile(filepath.Join(ws.Path, "CLAUDE.md"), "@AGENTS.md\n")
}

func rebaseRulesContext(repo models.RepoWorktree) error {
	if err := contextrepo.CheckRebase(repo); err != nil {
		return err
	}
	base, err := contextrepo.BaseBranch(repo)
	if err != nil {
		return err
	}
	_, behind, err := gitops.CommitsAheadBehind(repo.WorktreePath, base)
	if err != nil || behind == 0 {
		return err
	}
	if err := gitops.RebaseUnsigned(repo.WorktreePath, base); err != nil {
		return errors.Join(err, gitops.RebaseAbort(repo.WorktreePath))
	}
	return nil
}

func replaceRulesFile(path, content string) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".gw-rules-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err := f.WriteString(content); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(0o644); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}
